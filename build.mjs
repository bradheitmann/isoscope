#!/usr/bin/env node
/* isoscope builder — inject a spec into the engine template.
   Importable: buildHtml(spec) → html string.  Runnable: build.mjs <spec.json> <out.html> */
import { readFileSync, writeFileSync } from "fs";
import { createHash } from "crypto";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));

export function buildHtml(spec, { specLabel = "inline spec", meaningsPath = null } = {}) {
  const tpl = readFileSync(join(here, "template.html"), "utf8");
  if (!tpl.includes("__ISOSCOPE_SPEC__")) throw new Error("template missing spec slot");
  /* R-OP-6/R-OP-3 rule sheet 4.6: read + validate the meanings sidecar when it sits beside the
     adapter; apply copy.title to the spec in memory (adapter FILE stays byte-identical). */
  let meanings = "{}", sidecar = null;
  const mp = meaningsPath || String(specLabel).replace(/\.json$/i, "") + ".meanings.json";
  try {
    sidecar = JSON.parse(readFileSync(mp, "utf8"));
    const fail = r => { const e = new Error("MEANINGS_SIDECAR_INVALID: " + r); e.code = "MEANINGS_SIDECAR_INVALID"; throw e; };
    if (sidecar.for_sha256 && /\.json$/i.test(specLabel)) {
      const digest = createHash("sha256").update(readFileSync(specLabel, "utf8")).digest("hex");
      if (digest !== sidecar.for_sha256) fail("for_sha256 does not match the adapter file digest");
    }
    const nodeIds = new Set(spec.nodes.map(n => n.id));
    const edgeKeys = new Set(spec.edges.map(e => e[0] + "-" + e[1]));
    if (!sidecar.nodes) fail("missing nodes");
    for (const id of Object.keys(sidecar.nodes)) if (!nodeIds.has(id)) fail("sidecar node not in adapter: " + id);
    for (const id of nodeIds) if (!sidecar.nodes[id] || !sidecar.nodes[id].role || !sidecar.nodes[id].makes) fail("node missing role or makes: " + id);
    if (!sidecar.edges) fail("missing edges");
    for (const k of Object.keys(sidecar.edges)) if (!edgeKeys.has(k)) fail("sidecar edge not in adapter: " + k);
    for (const k of edgeKeys) if (!sidecar.edges[k] || !sidecar.edges[k].meaning) fail("edge missing meaning: " + k);
    const GR = ( ...p ) => new RegExp(p.join(""), "i");
    const banned = [GR("hon","est"), GR("load-","bearing"), GR("del","ve"), GR("seam","less"), GR("gen","uinely"), GR("nuan","ced"), GR("tape","stry"), GR("lever","ag"), GR("\\btru","ly\\b"), GR("\\bjour","ney\\b"), GR("\\belev","at"), GR("\\bcri","sp\\b"), GR("single ","source"," of ","truth")];
    const texts = [sidecar.copy && sidecar.copy.title, sidecar.copy && sidecar.copy.plan_purpose, sidecar.copy && sidecar.copy.plan_relations,
      ...Object.values(sidecar.groups || {}).map(g => g.purpose),
      ...Object.values(sidecar.nodes || {}).flatMap(n => [n.role, n.makes]),
      ...Object.values(sidecar.edges || {}).map(e => e.meaning)];
    for (const t of texts) if (t && banned.some(re => re.test(String(t)))) fail("banned word in sidecar text: " + String(t).slice(0, 40));
    meanings = JSON.stringify(sidecar).replace(/<\/script/gi, "<\\/script");
  } catch (e) { if (e.code === "MEANINGS_SIDECAR_INVALID") throw e; /* no sidecar beside this spec */ }
  const json = JSON.stringify(spec).replace(/<\/script/gi, "<\\/script");
  const island = json; /* no build-time copy overrides (Q1): words are fixed at their source */

  const routerSrc = readFileSync(join(here, "router.mjs"), "utf8").replace(/^export .*$/m, "");
  if (!tpl.includes("/*__ISOSCOPE_ROUTER__*/")) throw new Error("template missing router slot");
  const banner = `<!-- GENERATED by isoscope from ${specLabel} — do not hand-edit; edit the spec and rebuild. -->\n`;
  return tpl.replace("/*__ISOSCOPE_ROUTER__*/", routerSrc).replace("__ISOSCOPE_SPEC__", island).replace("__ISOSCOPE_MEANINGS__", meanings).replace(/^(<!doctype html>\s*\n?)/i, m => m + banner);
}

/* Provenance lock check — specs that carry a top-level `provenance` block must match a sibling
   `<spec>.lock.json` computed externally. Specs without `provenance` are untouched.
   Returns { ok: true } or { ok: false, reason }. Never opens the output path. */
const HEX40 = /^[0-9a-f]{40}$/, HEX64 = /^[0-9a-f]{64}$/;
const isPlainObject = v => v !== null && typeof v === "object" && !Array.isArray(v);
const validHex = (v, re) => typeof v === "string" && re.test(v) && /[^0]/.test(v);
export function validateProvenance(spec, specPath) {
  const prov = spec.provenance;
  if (prov === undefined) return { ok: true };
  const refuse = reason => ({ ok: false, reason });
  if (!isPlainObject(prov)) return refuse("provenance is not a plain object");
  if (typeof specPath !== "string" || !specPath.endsWith(".json")) return refuse("spec path must end in .json to locate the sibling lock");
  const lockPath = specPath.slice(0, -".json".length) + ".lock.json";
  let lockText;
  try { lockText = readFileSync(lockPath, "utf8"); } catch { return refuse(`missing lock ${lockPath}`); }
  let lock;
  try { lock = JSON.parse(lockText); } catch { return refuse(`lock JSON is malformed at ${lockPath}`); }
  if (!isPlainObject(lock) || !Array.isArray(lock.sources)) return refuse("lock JSON is malformed: expected an object with a sources array");
  for (const [key, re] of [["pinned_spec_head", HEX40], ["pinned_product_head", HEX40], ["spec_payload_root", HEX64]]) {
    if (!validHex(prov[key], re)) return refuse(`${key} is not ${re === HEX40 ? 40 : 64} lowercase hex or is all zeros`);
    if (prov[key] !== lock[key]) return refuse(`${key} differs from lock`);
  }
  if (!Array.isArray(prov.sources)) return refuse("sources is not an array");
  const pairSet = (list, label) => {
    const set = new Set();
    for (const s of list) {
      if (!isPlainObject(s) || typeof s.path !== "string" || !validHex(s.sha256, HEX64)) return refuse(`${label} source lacks a string path or a 64-lowercase-hex non-zero sha256`);
      const k = s.path + "\u0000" + s.sha256;
      if (set.has(k)) return refuse(`duplicate ${label} source ${s.path}`);
      set.add(k);
    }
    return set;
  };
  const specSet = pairSet(prov.sources, "spec"); if (specSet.ok === false) return specSet;
  const lockSet = pairSet(lock.sources, "lock"); if (lockSet.ok === false) return lockSet;
  if (specSet.size !== lockSet.size) return refuse(`source count ${specSet.size} differs from lock count ${lockSet.size}`);
  for (const k of specSet) if (!lockSet.has(k)) return refuse(`source not in lock: ${k.split("\u0000")[0]}`);
  for (const k of lockSet) if (!specSet.has(k)) return refuse(`lock source missing from spec: ${k.split("\u0000")[0]}`);
  return { ok: true };
}

const invokedDirectly = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (invokedDirectly) {
  const [, , specPath, outPath] = process.argv;
  if (!specPath || !outPath) { console.error("usage: build.mjs <spec.json> <out.html>"); process.exit(1); }
  const spec = JSON.parse(readFileSync(specPath, "utf8"));
  const prov = validateProvenance(spec, specPath);
  if (!prov.ok) { process.stderr.write(`PROVENANCE_REFUSAL: ${prov.reason}\n`); process.exit(2); }
  writeFileSync(outPath, buildHtml(spec, { specLabel: specPath }));
  console.log(`isoscope: built ${outPath} from ${specPath} · ${spec.nodes.length} modules · ${spec.edges.length} links`);
}
