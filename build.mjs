#!/usr/bin/env node
/* isoscope builder: inject a spec JSON into the engine template →
   one self-contained HTML that works over file:// (no server, no CORS). */
import {readFileSync,writeFileSync} from "fs";
import {dirname,join} from "path";
import {fileURLToPath} from "url";
const [,,specPath,outPath]=process.argv;
if(!specPath||!outPath){console.error("usage: node build.mjs <spec.json> <out.html>");process.exit(1);}
const here=dirname(fileURLToPath(import.meta.url));
const tpl=readFileSync(join(here,"template.html"),"utf8");
const spec=JSON.parse(readFileSync(specPath,"utf8")); // validates JSON
const json=JSON.stringify(spec).replace(/<\/script/gi,"<\\/script");
if(!tpl.includes("__ISOSCOPE_SPEC__")){console.error("template missing spec slot");process.exit(1);}
const banner="<!-- GENERATED by isoscope from "+specPath+" — do not hand-edit; edit the spec and rebuild. -->\n";
const out=tpl.replace("__ISOSCOPE_SPEC__",json).replace(/^(<!doctype html>\s*\n?)/i,(m)=>m+banner);
writeFileSync(outPath,out);
console.log("isoscope: built",outPath,"from",specPath,"·",spec.nodes.length,"modules ·",spec.edges.length,"links");
