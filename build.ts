#!/usr/bin/env bun
/* isoscope builder — inject a spec into the engine template.
   Importable: buildHtml(spec) → html string.  Runnable: bun build.ts <spec.json> <out.html>
   The shared router is authored in strict TypeScript (router.ts); the template needs plain
   JS, so it is transpiled (type erasure only) with Bun's built-in transpiler at build time. */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const transpiler = new Bun.Transpiler({ loader: "ts" });

/* router.ts as plain JS, with its trailing `export { ... }` line stripped (inlined into a <script>). */
function routerJs(): string {
  return transpiler.transformSync(readFileSync(join(here, "router.ts"), "utf8")).replace(/^export .*$/gm, "");
}

export function buildHtml(spec: unknown, { specLabel = "inline spec" }: { specLabel?: string } = {}): string {
  const tpl = readFileSync(join(here, "template.html"), "utf8");
  if (!tpl.includes("__ISOSCOPE_SPEC__")) throw new Error("template missing spec slot");
  const json = JSON.stringify(spec).replace(/<\/script/gi, "<\\/script");
  const routerSrc = routerJs();
  if (!tpl.includes("/*__ISOSCOPE_ROUTER__*/")) throw new Error("template missing router slot");
  const banner = `<!-- GENERATED by isoscope from ${specLabel} — do not hand-edit; edit the spec and rebuild. -->\n`;
  /* callback replacements: replacement text is literal, so `$&` / `$'` inside
     the spec JSON or router source can never act as replacement syntax (F18) */
  return tpl.replace("/*__ISOSCOPE_ROUTER__*/", () => routerSrc).replace("__ISOSCOPE_SPEC__", () => json).replace(/^(<!doctype html>\s*\n?)/i, m => m + banner);
}

if (import.meta.main) {
  const [specPath, outPath] = process.argv.slice(2);
  if (!specPath || !outPath) { console.error("usage: build.ts <spec.json> <out.html>"); process.exit(1); }
  const spec = JSON.parse(readFileSync(specPath, "utf8")) as { nodes: unknown[]; edges: unknown[] };
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, buildHtml(spec, { specLabel: specPath }));
  console.log(`isoscope: built ${outPath} from ${specPath} · ${spec.nodes.length} modules · ${spec.edges.length} links`);
}
