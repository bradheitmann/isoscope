import { describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "fs";
import { tmpdir } from "os";
import { join, resolve } from "path";
import { buildHtml } from "../build.ts";

const root = resolve(import.meta.dir, "..");
const specPath = join(root, "examples/isoscope.spec.json");
const spec = JSON.parse(readFileSync(specPath, "utf8"));

function run(cmd: string[], input?: string, env?: Record<string, string>) {
  const p = Bun.spawnSync(cmd, { cwd: root, env: env ? { ...process.env, ...env } : undefined, stdin: input ? new TextEncoder().encode(input) : undefined });
  return { code: p.exitCode, out: p.stdout.toString(), err: p.stderr.toString() };
}

describe("buildHtml", () => {
  test("embeds the spec and fills the router slot", () => {
    const html = buildHtml(spec, { specLabel: "probe" });
    expect(html).toContain("GENERATED by isoscope from probe");
    expect(html).toContain(JSON.stringify(spec.nodes[0].id));
    expect(html).not.toContain("__ISOSCOPE_SPEC__");
    expect(html).not.toContain("/*__ISOSCOPE_ROUTER__*/");
    expect(html).toContain("function isoRouteAll");
  });
});

describe("cli render", () => {
  test("creates the output (and its parent dir) and leaves no temp store", () => {
    const dir = mkdtempSync(join(tmpdir(), "isoscope-test-"));
    try {
      const out = join(dir, "nested/deeper/map.html");
      const scratch = join(dir, "tmp");
      mkdirSync(scratch);
      const r = run(["bun", "cli.ts", "render", specPath, out], undefined, { TMPDIR: scratch });
      expect(r.code).toBe(0);
      expect(readdirSync(scratch)).toEqual([]); // mkdtemp store removed
      expect(existsSync(out)).toBe(true);
      expect(readFileSync(out, "utf8")).toContain("GENERATED by isoscope");
    } finally { rmSync(dir, { recursive: true, force: true }); }
  });
});

describe("drc", () => {
  test("passes on the odin example spec", () => {
    const r = run(["bun", "drc.ts", join(root, "examples/odin.spec.json")]);
    expect(r.code).toBe(0);
    expect(r.out).toContain("PASS");
  });
});

describe("mcp", () => {
  test("tools/list answers over stdio", () => {
    const dir = mkdtempSync(join(tmpdir(), "isoscope-test-"));
    try {
      const req = JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list" }) + "\n";
      const p = Bun.spawnSync(["bun", "mcp.ts", join(dir, "m.db")], { cwd: root, stdin: new TextEncoder().encode(req) });
      expect(p.exitCode).toBe(0);
      const names = p.stdout.toString().split("\n").filter(Boolean).map(l => JSON.parse(l))
        .flatMap(m => m.result?.tools ?? []).map((t: { name: string }) => t.name);
      expect(names).toContain("iso_overview");
      expect(names).toContain("iso_get_spec");
    } finally { rmSync(dir, { recursive: true, force: true }); }
  });
});
